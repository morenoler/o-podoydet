import type { FeatureId, Preference, Trip } from "./types";

export type AdvisorMode = "rules" | "local";
export type AdvisorStatus =
  "queued" | "running" | "completed" | "failed" | "cancelled";
export interface AdvisorEvidence {
  id: string;
  feature: FeatureId | "capacity" | "floor" | "window_direction";
  label: string;
  required: boolean;
  status: "match" | "mismatch";
  evidenceStatus: string;
  assumed: boolean;
  explanation: string;
  sources: { url: string; label: string }[];
}
export interface AdvisorCandidate {
  provisional?: boolean;
  id: string;
  hotelId: string;
  hotelName: string;
  roomId: string;
  roomName: string;
  status: "fits" | "excluded";
  score: number;
  criteria: AdvisorEvidence[];
}
export interface AdvisorScenario {
  id: string;
  feature: FeatureId;
  label: string;
  kind: "optional_priority" | "requires_consent";
  count: number;
  gainedCount: number;
  candidateIds: string[];
  explanation: string;
}
export interface AdvisorQuestion {
  id: string;
  text: string;
  reason: string;
  feature?: FeatureId;
}
/** All facts and scenario counts originate from the Java matching engine. */
export interface AdvisorContext {
  searchId: string;
  trip: Trip;
  preferences: Preference[];
  totalHotels: number;
  fitCount: number;
  conflicts: string[];
  warnings: string[];
  candidates: AdvisorCandidate[];
  /** All synthetic listings from the same Java search snapshot, including excluded ones. */
  testCases?: AdvisorCandidate[];
  scenarios: AdvisorScenario[];
  questions: AdvisorQuestion[];
  generatedAt: string;
}
export interface AdvisorEvent {
  agent: "coordinator" | "needs" | "selector" | "critic";
  status: "running" | "completed" | "warning";
  detail: string;
  at: string;
}
export interface AdvisorReport {
  outcome: "shortlist" | "no_matches" | "clarification_needed";
  summary: string;
  candidateIds: string[];
  scenarioIds: string[];
  questionId: string | null;
  cautions: { candidateId: string; evidenceIds: string[] }[];
  nextSteps: string[];
}
export interface AdvisorRun {
  execution?: "rules" | "local" | "rules_fallback";
  model?: string;
  diagnostics?: AdvisorDiagnostic[];
  id: string;
  mode: AdvisorMode;
  status: AdvisorStatus;
  createdAt: string;
  updatedAt: string;
  context: AdvisorContext;
  events: AdvisorEvent[];
  report: AdvisorReport | null;
  modelCalls: number;
  inputTokens: number;
  outputTokens: number;
  warnings: string[];
  error?: string;
}
/** Observable tool I/O only; never private model reasoning. */
export interface AdvisorDiagnostic {
  id: string;
  agent: "selector" | "critic";
  status: "running" | "completed" | "failed";
  startedAt: string;
  finishedAt?: string;
  durationMs?: number;
  model: string;
  input: unknown;
  /** Alias decoding metadata generated by Python; not part of the model prompt. */
  references?: {
    candidates: Record<string, string>;
    evidence: Record<string, [string, string]>;
    scenarios: Record<string, string>;
    questions: Record<string, string>;
  };
  output?: unknown;
  inputTokens?: number;
  outputTokens?: number;
  error?: string;
}
export interface AdvisorConfig {
  modes: AdvisorMode[];
  defaultMode: "rules";
  maxModelCalls: number;
  model: string;
}
